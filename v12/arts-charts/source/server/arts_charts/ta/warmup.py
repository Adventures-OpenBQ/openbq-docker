"""Study warm-up: a port of bdobb-v2's `src/lib/chart/warmup.ts`.

The Art's Charts card asks its study socket for history BEFORE the visible
window, so the first visible point of an SMA(200) is an average of 200 bars,
not of the handful the window happens to start with. The card computed that
earlier start itself. The Charts MCP needs the very same start -- an EMA seeded
from a different first bar is a different line, and the spec promises a model
the card's values exactly -- so the rule now lives here too, behind
`warmup=auto` on `/ta_series_ws` and `/ta_snapshot` (Charts MCP macros spec,
2026-10-01), and the card switches to asking for it.

This is a PORT, not a redesign: every quirk is warmup.ts's, kept on purpose.
A window value's leading integer is read the way JavaScript's `parseInt`
reads it (`"50bd"` is 50, `14.7` is 14, `"wat"` is nothing); an interval the
pattern does not read counts as one minute; a symbol with no calendar is
padded as if it traded a 6.5h session. tests/test_ta_warmup.py holds this file
to fixtures generated BY warmup.ts, so any drift between the two is a failing
test rather than a chart that is quietly different in one client.
"""

from __future__ import annotations

import math
import re
from collections.abc import Callable, Iterable
from datetime import date, timedelta

#: Three window lengths behind the first visible point (warmup.ts WARMUP_FACTOR).
WARMUP_FACTOR = 3
#: A calendar-less symbol is padded as if it traded a SHORT session: fewer
#: bars per day means more days of padding, and over-fetching is the safe side.
NO_CALENDAR_SESSION_SECONDS = 6.5 * 3600
#: Slack over the 7/5 weekday estimate, for holidays.
HOLIDAY_SLACK_DAYS = 2

_UNIT_SECONDS = {"s": 1, "m": 60, "h": 3600, "d": 86400, "w": 604800}
_INTERVAL = re.compile(r"(\d+)([smhdw])")
_INTRADAY = re.compile(r"\d+[smh]")
#: `parseInt(String(value), 10)`: optional leading space and sign, then digits.
_LEADING_INT = re.compile(r"\s*([+-]?\d+)")


def _window_integer(value) -> int | None:
    """The leading integer of a window value, or None -- JavaScript's parseInt.

    `str()` stands in for `String()`: the two agree on every value a study
    parameter can hold here (ints, floats, `"50bd"` strings, None/undefined),
    including `1e+21`, which both print in exponent form and both read as 1.
    """
    match = _LEADING_INT.match(str(value))
    return int(match.group(1)) if match else None


def warmup_bars(series: Iterable[dict], windows_of: Callable[[str], list[str] | None]) -> int:
    """How many bars of warm-up a chart's studies need (warmup.ts `warmupBars`).

    Per study, the SUM of its window values (MACD's signal runs on the MACD
    line, so slow + signal, not their max); across studies, the MAX of those
    sums; times WARMUP_FACTOR. `windows_of(name)` names a study's window
    params, or returns None for a study the registry does not carry, which
    contributes nothing. A series whose `type` is not "study" contributes
    nothing either.
    """
    best = 0
    for entry in series:
        if entry.get("type", "study") != "study":
            continue
        windows = windows_of(entry["name"])
        if windows is None:
            continue
        params = entry.get("params") or {}
        total = sum(n for n in (_window_integer(params.get(w)) for w in windows) if n is not None)
        best = max(best, total)
    return best * WARMUP_FACTOR


def _interval_seconds(interval: str) -> int:
    match = _INTERVAL.fullmatch(interval)
    return 60 if match is None else int(match.group(1)) * _UNIT_SECONDS[match.group(2)]


#: Sessions in one daily-or-longer bar, per unit: the range cap's counts (window.ts
#: budgetSessions: a week five, a month twenty-one).
_SESSIONS_PER_UNIT = {"d": 1, "w": 5, "M": 21}
_COARSE = re.compile(r"(\d+)([dwM])")


def _sessions_per_bar(interval: str) -> int:
    """`nd` n sessions, `nw` 5n, `nM` 21n (warmup.ts `sessionsPerBar`); 1 for anything else."""
    match = _COARSE.fullmatch(interval)
    return 1 if match is None else int(match.group(1)) * _SESSIONS_PER_UNIT[match.group(2)]


def pad_start(start: str, bars: int, interval: str, session_seconds: float | None) -> str:
    """`start` (YYYY-MM-DD) moved earlier by enough calendar days for `bars`
    bars of warm-up (warmup.ts `padStart`).

    `session_seconds` is the regular session's length on `start`'s own date --
    what the card's exchange calendar gives -- or None for a symbol with no
    calendar. A daily-or-longer bar spans the sessions it holds (`_sessions_per_bar`:
    a day one, a week five, a month twenty-one); an intraday interval fits as many
    bars as the session holds. Trading days become calendar days at 7/5,
    rounded up, plus HOLIDAY_SLACK_DAYS. Pure date arithmetic: the same window
    always pads to the same start.
    """
    if bars == 0:
        return start
    seconds = NO_CALENDAR_SESSION_SECONDS if session_seconds is None else session_seconds
    per_day = (max(1, math.floor(seconds / _interval_seconds(interval)))
               if _INTRADAY.fullmatch(interval) else 1)
    trading_days = math.ceil(bars / per_day) * _sessions_per_bar(interval)
    calendar_days = math.ceil(trading_days * 7 / 5) + HOLIDAY_SLACK_DAYS
    year, month, day = (int(part) for part in start.split("-"))
    return (date(year, month, day) - timedelta(days=calendar_days)).isoformat()
