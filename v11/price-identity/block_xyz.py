"""Qualification-only exporter for one explicitly bounded Block example.

Checks retained evidence integrity and a declared operator assertion. Does not
certify historical identity, fetch sources or write the Security Master.
"""
import argparse
from hashlib import sha256
from html.parser import HTMLParser
import json
from pathlib import Path
from uuid import UUID

PROJECTION='security-master-projection/1:admission-floor-1:276020d132c6d2b856cafe6b4bda00b8ab9eae8d011ad8df6b997897565e269b:2026-11-03T21:54:38.454117Z'
SOURCES={'general','rename','announcement','security_master'}


def require(ok):
    if not ok:raise ValueError('unqualified bounded Block identity evidence')


def canonical(value):return json.dumps(value,sort_keys=True,separators=(',',':')).encode()


def strict_json(raw):
    def pairs(items):
        result={}
        for key,value in items:
            require(key not in result);result[key]=value
        return result
    def nonfinite(value):raise ValueError('nonfinite source JSON')
    return json.loads(raw.decode('utf8'),object_pairs_hook=pairs,parse_constant=nonfinite)


class Text(HTMLParser):
    def __init__(self):super().__init__(convert_charrefs=True);self.parts=[]
    def handle_data(self,data):self.parts.append(data)


def validate_example(manifest,bodies):
    require(manifest.get('schema_version')==1 and manifest.get('identity_basis')=='provisional_provider_symbol' and
        manifest.get('business_history_qualified') is False and manifest.get('index_membership_qualified') is False and
        manifest.get('issuer_cik')=='0001512673' and manifest.get('security_master_projection')==PROJECTION)
    sources=manifest.get('sources',{})
    require(set(sources)==SOURCES and set(bodies)==SOURCES)
    for name,raw in bodies.items():
        require(isinstance(raw,bytes) and 0<len(raw)<=2097152 and
            sha256(raw).hexdigest()==sources[name].get('sha256'))
    general=strict_json(bodies['general'])
    require(all(general.get(key)==value for key,value in
        {'Code':'XYZ','Exchange':'NYSE','CurrencyCode':'USD','CIK':'0001512673'}.items()))
    renames=strict_json(bodies['rename'])
    require(isinstance(renames,list))
    matched=[row for row in renames if isinstance(row,dict) and row.get('exchange')=='US' and row.get('new_symbol')=='XYZ']
    require(len(matched)==1 and matched[0].get('old_symbol')=='SQ' and matched[0].get('effective')=='2025-01-21')
    text=Text();text.feed(bodies['announcement'].decode('utf8'))
    plain=' '.join(' '.join(text.parts).split())
    require(all(word in plain for word in ('NYSE','SQ','XYZ','January 21, 2025','CUSIP','unchanged')))
    response=strict_json(bodies['security_master']);rows=response.get('results',[])
    require(len(rows)==1 and rows[0].get('symbol')=='XYZ')
    row=rows[0]
    for key in ('issuer_id','listing_id','security_id'):UUID(row[key])
    # These IDs are returned by the admitted source, not generated by the exporter.
    require(row['issuer_id']=='889177af-a7b8-5ecc-b28a-709f38056d7f' and
        row['listing_id']=='b26c051d-9380-5edb-9496-abce1acc0376' and
        row['security_id']=='0ded9da3-748c-5505-9d4e-299bc74575be')
    receipt=response.get('extra',{}).get('security_master_receipt',{})
    require(receipt.get('projection_version')==PROJECTION and receipt.get('temporal_mode')=='current_corrected' and
        receipt.get('availability_policy')=='local_as_ingested' and receipt.get('effective_at') is None and receipt.get('known_at') is None)
    expected=[{'symbol':'XYZ.US','listing_id':row['listing_id'],'issuer_id':row['issuer_id'],
        'start':'2025-01-21','end':'2025-01-22'}]
    require(manifest.get('mappings')==expected)
    return {'schema_version':1,'mappings':expected,'identity_map_sha256':sha256(canonical(expected)).hexdigest(),
        'evidence_manifest_sha256':sha256(canonical(manifest)).hexdigest(),'identity_basis':'provisional_provider_symbol',
        'business_history_qualified':False,'index_membership_qualified':False,
        'window_basis':'issuer-announced NYSE ticker transition; one-day operator assertion'}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest',required=True,type=Path)
    parser.add_argument('--bodies-dir',required=True,type=Path)
    parser.add_argument('--output',required=True,type=Path)
    args=parser.parse_args()
    manifest=strict_json(args.manifest.read_bytes());bodies={}
    for name,item in manifest['sources'].items():
        filename=item['filename']
        require(isinstance(filename,str) and Path(filename).name==filename and filename not in {'.','..'})
        path=args.bodies_dir/filename
        require(not path.is_symlink() and path.stat().st_size<=2097152)
        bodies[name]=path.read_bytes()
    result=validate_example(manifest,bodies)
    # Refuse replacement of an earlier reviewed export.
    with args.output.open('x') as stream:json.dump(result,stream,indent=2);stream.write('\n')
    args.output.chmod(0o600)
    print(json.dumps({'status':'bounded_operator_identity_exported','identity_map_sha256':result['identity_map_sha256'],
        'business_history_qualified':False,'identity_basis':result['identity_basis']}))


if __name__=='__main__':main()
